@app.route("/story", methods=["GET", "POST"])
def story():
    data = request.form if request.method == "POST" else request.args
    emotion = data.get("emotion", DEFAULT_EMOTION)
    keyword = data.get("keyword", "")
    title, body = generate_story(emotion, keyword)
    if emotion not in FRAGMENTS:
        emotion = DEFAULT_EMOTION
    story_html = "".join(
        "<p>" + html.escape(p) + "</p>" for p in body.split("\n\n")
    )
    return render_template_string(
        INDEX_HTML,
        emotions=EMOTIONS,
        selected=emotion,
        keyword=keyword,
        title=title,
        emotion=emotion,
        length=len(body),
        story_html=story_html,
    )


