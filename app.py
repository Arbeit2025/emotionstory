# 4. 物語生成ロジック
# ============================


def generate_story(emotion, keyword=""):
    """感情と任意キーワードから (タイトル, 本文) を生成する。

    導入・情景・中盤×2・結びをランダムに組み合わせ、場所・小物・時間帯を
    織り込む。本文は MIN_LENGTH〜MAX_LENGTH 字に収まるよう調整する。
    不正な感情値は DEFAULT_EMOTION にフォールバックする。
    """
    if emotion not in FRAGMENTS:
        emotion = DEFAULT_EMOTION
    keyword = (keyword or "").strip().replace("\n", " ")[:30]

    rng = random.Random()
    pool = FRAGMENTS[emotion]
    place = rng.choice(PLACES)
    item = rng.choice(ITEMS)
    time = rng.choice(TIMES)

    def fill(text):
        return text.format(place=place, item=item, time=time)

    intro = fill(rng.choice(pool["intro"]))
    scene = fill(rng.choice(SCENES))
    middles = [fill(m) for m in rng.sample(pool["middle"], 2)]
    ending = fill(rng.choice(pool["ending"]))
    rest_middles = [fill(m) for m in pool["middle"] if fill(m) not in middles]

    parts = [intro, scene, middles[0]]
    if keyword:
        kw_line = rng.choice(KEYWORD_LINES).format(keyword=keyword)
        parts.append(kw_line)
    parts.append(middles[1])
    parts.append(ending)

    # 文字数の調整：短ければ中盤の断片を結びの前に追加、長ければ情景を落とす
    def total(ps):
        return len("\n\n".join(ps))

    while total(parts) < MIN_LENGTH and rest_middles:
        parts.insert(len(parts) - 1, rest_middles.pop(0))
    if total(parts) > MAX_LENGTH and scene in parts:
        parts.remove(scene)

    body = "\n\n".join(parts)
    title = fill(rng.choice(pool["titles"]))
    return title, body


